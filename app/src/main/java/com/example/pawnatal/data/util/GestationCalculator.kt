package com.example.pawnatal.data.util

import com.example.pawnatal.data.model.DamProfile
import com.example.pawnatal.data.model.ObstetricCarePlan
import com.example.pawnatal.data.model.ObstetricInsights
import java.time.LocalDate
import java.time.format.DateTimeFormatter
import java.time.temporal.ChronoUnit
import java.util.Locale

object GestationCalculator {

    val dtfLong: DateTimeFormatter = DateTimeFormatter.ofPattern("d MMMM yyyy", Locale.ENGLISH)
    val dtfMedium: DateTimeFormatter = DateTimeFormatter.ofPattern("dd MMM yyyy", Locale.ENGLISH)
    val dtfShort: DateTimeFormatter = DateTimeFormatter.ofPattern("d MMM", Locale.ENGLISH)
    val dtfIndian: DateTimeFormatter = DateTimeFormatter.ofPattern("dd/MM/yyyy", Locale.ENGLISH)
    val dtfIso: DateTimeFormatter = DateTimeFormatter.ofPattern("yyyy-MM-dd", Locale.ENGLISH)

    fun parseMatingDate(dateStr: String): LocalDate {
        val trimmed = dateStr.trim()
        val formatters = listOf(
            dtfIso,
            dtfIndian,
            DateTimeFormatter.ofPattern("dd-MM-yyyy", Locale.ENGLISH),
            dtfMedium,
            dtfLong
        )
        for (formatter in formatters) {
            try {
                return LocalDate.parse(trimmed, formatter)
            } catch (_: Exception) {}
        }
        return try {
            LocalDate.parse(trimmed)
        } catch (_: Exception) {
            LocalDate.now()
        }
    }

    fun calculateInsights(
        matingDateStr: String,
        breed: String,
        existingInsights: ObstetricInsights? = null,
        asOfDate: LocalDate = LocalDate.now()
    ): ObstetricInsights {
        val matingDate = if (matingDateStr.isNotBlank()) parseMatingDate(matingDateStr) else asOfDate.minusDays(1)
        val daysBetween = ChronoUnit.DAYS.between(matingDate, asOfDate).toInt()
        val currentDay = (daysBetween + 1).coerceIn(1, 65)
        val currentWeek = ((currentDay - 1) / 7 + 1).coerceIn(1, 9)
        val currentTrimester = when {
            currentDay <= 21 -> 1
            currentDay <= 42 -> 2
            else -> 3
        }
        val whelpDate = matingDate.plusDays(63)
        val daysRemaining = maxOf(0, 63 - currentDay)
        val percentComplete = ((currentDay.toFloat() / 63f) * 100).toInt().coerceIn(1, 100)

        val trimesterDescription = when (currentTrimester) {
            1 -> "Trimester I: Embryonic Cleavage & Uterine Implantation (Days 1–21)"
            2 -> "Trimester II: Fetal Organogenesis & Skeleton Hardening (Days 22–42)"
            else -> "Trimester III: Rapid Fetal Growth & Whelping Readiness (Days 43–63)"
        }

        val cleanLitterSize = existingInsights?.estimatedLitterSize?.takeIf { it.isNotBlank() }?.let { raw ->
            val match = Regex("""(\d+[\s–-]+\d+\s*(?:puppies|pups)?)""", RegexOption.IGNORE_CASE).find(raw)
            if (match != null) {
                match.value.trim()
            } else if (raw.length > 18) {
                raw.take(16).trim() + "…"
            } else {
                raw.trim()
            }
        } ?: "1–4 puppies"

        val cleanLitterSubtitle = existingInsights?.litterSubtitle?.takeIf { it.isNotBlank() }?.let { raw ->
            if (raw.length > 28) raw.take(26).trim() + "…" else raw
        } ?: "$breed typical range"

        return ObstetricInsights(
            gestationSpanDays = 63,
            gestationRangeText = "Range: 61–65 days",
            estimatedWhelpDate = whelpDate.format(dtfLong),
            currentDay = currentDay,
            currentWeek = currentWeek,
            currentTrimester = currentTrimester,
            percentComplete = percentComplete,
            daysRemaining = daysRemaining,
            estimatedLitterSize = cleanLitterSize,
            litterSubtitle = cleanLitterSubtitle,
            trimesterDescription = trimesterDescription,
            tieDateDisplay = matingDate.format(dtfShort),
            todayDisplay = "Day $currentDay (${asOfDate.format(dtfShort)})",
            dueDisplay = whelpDate.format(dtfShort)
        )
    }

    /**
     * Reconciles any plan (whether generated by AI or loaded from disk)
     * so that all timeline dates, currentDay, and appointments are strictly
     * relative to firstMatingDate and today's date.
     */
    fun reconcileCarePlan(
        plan: ObstetricCarePlan,
        dam: DamProfile,
        asOfDate: LocalDate = LocalDate.now()
    ): ObstetricCarePlan {
        val effectiveMatingDate = if (dam.firstMatingDate.isNotBlank()) dam.firstMatingDate else asOfDate.minusDays(1).toString()
        val matingDate = parseMatingDate(effectiveMatingDate)
        val insights = calculateInsights(effectiveMatingDate, dam.breed, plan.insights, asOfDate)

        // Reconcile veterinary visits relative to matingDate
        val updatedVisits = plan.veterinaryVisits.mapIndexed { index, visit ->
            val visitDay = when (index) {
                0 -> 28 // Day 28 Gestation ultrasound
                1 -> 50 // Day 50 Puppy count x-ray
                2 -> 56 // Day 56 Pre-labor check
                else -> 28 + (index * 14)
            }
            val visitDate = matingDate.plusDays(visitDay.toLong())
            val daysUntil = ChronoUnit.DAYS.between(asOfDate, visitDate).toInt()
            val status = when {
                daysUntil < 0 -> "COMPLETED"
                daysUntil == 0 -> "TODAY"
                else -> "UPCOMING"
            }
            visit.copy(
                isoDate = visitDate.format(dtfIso),
                scheduledDateText = "${visitDate.format(dtfLong)} (Day $visitDay)",
                daysUntil = maxOf(0, daysUntil),
                status = status,
                doctorName = if (dam.vetDoctorName.isNotBlank()) {
                    dam.vetDoctorName
                } else if (visit.doctorName.contains("Thorne", ignoreCase = true) || visit.doctorName.contains("Harrison", ignoreCase = true) || visit.doctorName.isBlank()) {
                    "Primary Veterinarian"
                } else {
                    visit.doctorName
                },
                clinicName = if (dam.vetClinicName.isNotBlank()) {
                    dam.vetClinicName
                } else if (visit.clinicName.contains("Oakridge", ignoreCase = true) || visit.clinicName.contains("Metro", ignoreCase = true) || visit.clinicName.isBlank()) {
                    "Attending Clinic"
                } else {
                    visit.clinicName
                },
                address = if (dam.vetClinicAddress.isNotBlank()) dam.vetClinicAddress else visit.address
            )
        }

        // Reconcile milestones relative to matingDate
        val updatedMilestones = plan.milestones.mapIndexed { index, milestone ->
            val milestoneDay = when (index) {
                0 -> 28
                1 -> 50
                2 -> 56
                3 -> 63
                else -> 28 + (index * 10)
            }
            val milestoneDate = matingDate.plusDays(milestoneDay.toLong())
            val isCompleted = insights.currentDay >= milestoneDay
            val window = if (milestone.dayWindow.isNotBlank() && (milestone.dayWindow.contains("Day", ignoreCase = true) || milestone.dayWindow.contains("–") || milestone.dayWindow.contains("-"))) {
                milestone.dayWindow
            } else {
                "Day $milestoneDay • ${milestoneDate.format(dtfShort)}"
            }
            milestone.copy(
                dayWindow = window,
                isCompleted = isCompleted
            )
        }

        // Reconcile emergency info with dam's saved clinic details
        val updatedEmergency = plan.emergencyInfo.copy(
            clinicName = if (dam.vetClinicName.isNotBlank()) {
                dam.vetClinicName
            } else if (plan.emergencyInfo.clinicName.contains("Oakridge", ignoreCase = true) || plan.emergencyInfo.clinicName.contains("Metro", ignoreCase = true) || plan.emergencyInfo.clinicName.isBlank()) {
                "Emergency Veterinary Hospital"
            } else {
                plan.emergencyInfo.clinicName
            },
            hotlinePhone = if (dam.emergencyPhone.isNotBlank()) {
                dam.emergencyPhone
            } else if (dam.vetClinicPhone.isNotBlank()) {
                dam.vetClinicPhone
            } else if (plan.emergencyInfo.hotlinePhone.contains("555")) {
                ""
            } else {
                plan.emergencyInfo.hotlinePhone
            },
            onDutyDoctor = if (dam.vetDoctorName.isNotBlank()) {
                dam.vetDoctorName
            } else if (plan.emergencyInfo.onDutyDoctor.contains("Thorne", ignoreCase = true) || plan.emergencyInfo.onDutyDoctor.contains("Harrison", ignoreCase = true) || plan.emergencyInfo.onDutyDoctor.isBlank()) {
                "Emergency Veterinarian"
            } else {
                plan.emergencyInfo.onDutyDoctor
            }
        )

        return plan.copy(
            insights = insights,
            veterinaryVisits = updatedVisits,
            milestones = updatedMilestones,
            emergencyInfo = updatedEmergency
        )
    }
}
